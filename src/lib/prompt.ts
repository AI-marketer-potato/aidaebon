import type { GenerateRequest, Reference } from "./types";

/**
 * 서비스의 심장 — 대본 생성 프롬프트.
 * 어드민이 등록한 레퍼런스(터진 릴스 예시)를 few-shot 으로 녹여,
 * 사용자가 고른 업종/지역/목적/톤에 100% 맞춘 릴스 대본을 만들어낸다.
 */

const SYSTEM_PROMPT = `너는 대한민국 최고의 숏폼(릴스·쇼츠·틱톡) 바이럴 마케팅 전략가이자 대본 작가다.
수백 개의 조회수 터진 영상을 분석해 "왜 터졌는지"를 공식으로 체화하고 있다.

[바이럴 공식 — 항상 적용]
1. 0~3초 후크가 전부다. 스크롤을 멈추게 하는 강력한 첫 자막/첫 마디로 시작한다.
2. 호기심 갭·공감 떡밥·반전으로 끝까지 보게 만든다 (이탈 방지).
3. 정보(저장 욕구) + 재미/도파민(공유 욕구)을 결합한다.
4. 소상공인이 스마트폰으로 직접 찍을 수 있는 현실적인 장면만 제시한다.
5. 명확한 CTA(저장·댓글·DM·방문·예약)로 행동을 유도한다.

[작성 규칙]
- 반드시 한국어로 작성한다.
- 업종·지역·목적·톤에 100% 맞춤화한다. 지역명을 자연스럽게 녹여 로컬 고객을 저격한다.
- [참고 후보]에는 여러 업종의 "터진 릴스" 예시가 섞여 주어진다. 먼저 이번 업체의 업종·지역·목적·톤에 비추어 **가장 잘 맞는 1~3개를 스스로 고른다** (같은 업종이 아니어도 후크 패턴·타깃·상황이 통하면 된다). 고른 예시의 "후크 패턴·구성·호흡"을 학습해 응용하되, 절대 문장을 그대로 베끼지 않는다.
- 어떤 레퍼런스를 골랐는지는 결과에 절대 쓰지 않는다. 완성된 대본만 [출력 형식]대로 출력한다.
- 과장·허위 광고 표현은 쓰지 않는다. 실제 매장이 지킬 수 있는 선에서 작성한다.
- 아래 [출력 형식]을 정확히 따른 마크다운으로만 답한다. 서론·잡담 없이 바로 결과부터 출력한다.

[출력 형식]
## 🎬 이번 콘셉트
**(콘셉트명)** — 한 줄 설명
(가장 효과적일 콘셉트 단 하나만 정한다. 여러 개를 나열하지 말고, 아래는 그 하나의 풀 대본이다.)

## 🪝 후크 (0–3초)
- **화면 자막:** (스크롤 멈추게 하는 강력한 한 줄)
- **멘트/나레이션:** (실제로 말할 대사)

## 🎞 장면별 대본
각 씬을 아래 형식으로 4~7개 작성:

**씬 1 · (예상 길이)초**
- 🎥 화면/연출: ...
- 💬 자막: ...
- 🎙 멘트: ...

## 📣 CTA (마무리)
(저장/방문/예약/DM 등 목적에 맞는 행동 유도 멘트 + 화면 자막)

## ✍️ 업로드 캡션 & 해시태그
- **캡션:** (감성 + 후킹 + CTA 포함 2~4줄)
- **해시태그:** #로컬 #업종 #지역 등 10~15개 (지역·업종 기반 실제 검색되는 태그 위주)

## 🎯 촬영·편집 꿀팁
- (이 영상의 조회수를 끌어올릴 촬영/편집/음악/자막 팁 3~5개)`;

/** 레퍼런스를 프롬프트에 넣을 텍스트 블록으로 변환 */
function buildReferenceBlock(refs: Reference[]): string {
  if (refs.length === 0) {
    return "(등록된 레퍼런스 없음 — 위의 바이럴 공식만으로 최고 수준의 대본을 작성하라.)";
  }
  return refs
    .map((r, i) => {
      const note = r.note ? `\n[왜 터졌나] ${r.note}` : "";
      return `### 참고 ${i + 1}. ${r.title}  (업종: ${r.industry})\n${r.content}${note}`;
    })
    .join("\n\n---\n\n");
}

export interface ChatMessage {
  role: "system" | "user";
  content: string;
}

/** OpenAI Chat Completions 용 메시지 배열 생성 */
export function buildMessages(
  req: GenerateRequest,
  refs: Reference[],
): ChatMessage[] {
  const tone = req.tone?.trim() || "업종에 가장 잘 맞는 톤으로 자유롭게";
  const extra = req.extra?.trim()
    ? `- 추가 요청사항: ${req.extra.trim()}`
    : "";

  const userPrompt = `아래 업체 정보에 맞춰 "조회수 터지는" 릴스 대본을 만들어줘.

[업체 정보]
- 업종: ${req.industry}
- 지역: ${req.region}
- 제작 목적: ${req.purpose}
- 원하는 톤: ${tone}
${extra}

[참고 후보 — 여러 업종의 터진 릴스 예시. 이 중 이번 업체에 가장 잘 맞는 1~3개를 직접 골라 응용할 것]
${buildReferenceBlock(refs)}

위 후보 중 이번 업체(${req.industry} · ${req.region} · ${req.purpose})에 가장 잘 맞는 것을 스스로 골라
그 성공 패턴을 학습·응용하되 그대로 베끼지 말고,
${req.region} 지역의 "${req.industry}" 업체가 "${req.purpose}" 목적으로 바로 촬영할 수 있는
완성도 높은 대본을 [출력 형식]에 맞춰 작성해줘. (어떤 레퍼런스를 골랐는지는 출력하지 말 것)`;

  return [
    { role: "system", content: SYSTEM_PROMPT },
    { role: "user", content: userPrompt },
  ];
}
